import re

def repair_santachi_whitelist(text):
    if not text:
        return ""
    t = text

    # 1. プレイスタイル・成績等の名詞前の「さんの」修飾語 ➔ 「選手の」
    t = re.sub(r'さんの(?=プレー|活躍|投打|成績|パフォーマンス|力|メンタル|心|練習|試合|出場|契約|移籍|引退|復帰|負傷|怪我)', '選手の', t)

    # 2. ホワイトリスト（人名、親族・一般呼称）
    # 親族・一般呼称は保護
    # 例: お父さんたち、お母さんたち、皆さんたち、お客さんたち、子どもさんたち、お子さんたち、奥さんたち、旦那さんたち
    SAFE_GENERAL = r'(?:お父|お母|お兄|お姉|おじ|おば|おじい|おばあ|みな|皆|お客|子ども|お子|奥|旦那)さん(?:たち|ら)'

    # 3. 助詞「の」直後の「さんたち」は100%日本語として不正（例: ファームのさんたち、巨人のさんたち、ベンチ裏のさんたち、合宿のさんたち、高校のさんたち）
    # 「〇〇のさんたち」➔「〇〇の選手たち」
    t = re.sub(r'のさんたち', 'の選手たち', t)
    t = re.sub(r'のさん(?=(?:への|へ|に|が|は|を|で|と|も|より|から|\b))', 'の選手', t)

    # 4. 助詞・句読点・文頭の直後に孤立した「さんたち」「さん（助詞）」
    # （例: にさんたち、へさんたち、とさんたち、^さんたち、。さんたち）
    t = re.sub(r'(?:^|(?<=[がはのにをとでへからもやよりから\s　、。！？（(]))さんたち', '選手たち', t)
    t = re.sub(r'(?:^|(?<=[がはのにをとでへからもやよりから\s　、。！？（(]))さん(?=(?:への|へ|に|が|は|を|で|と|も|より|から|\b))', '選手', t)

    # 5. 連体形（動詞・助動詞の過去形・連体形・進行形・状態）直後の「さんたち」「さん」
    # 日本語で「〜た」「〜だ」「〜る」「〜う」「〜く」「〜す」「〜つ」「〜ぬ」「〜む」「〜ぐ」「〜ぶ」「〜中」「〜ない」「〜たい」に「さん」が付くことはあり得ない（100%不正）
    # （例: 調整中だったさんたち、合流したさんたち、目指すさんたち、戦うさんたち、残留したさんたち、出場したさんたち）
    t = re.sub(r'((?:た|だ|る|う|く|す|つ|ぬ|む|ぐ|ぶ|ない|たい|ている|ていた|だった|である|中))さんたち', r'\1選手たち', t)
    t = re.sub(r'((?:た|だ|る|う|く|す|つ|ぬ|む|ぐ|ぶ|ない|たい|ている|ていた|だった|である|中))さん(?=(?:への|へ|に|が|は|を|で|と|も|より|から|\b))', r'\1選手', t)

    # 6. 「〇〇さんたち」を包括的にスキャンし、ホワイトリスト外（非人名・組織・役職・カテゴリー等）を自動判定
    # 日本人名（漢字1〜4文字）やカタカナ人名以外の一般名詞＋さんたちを救済
    def santachi_repl(m):
        prefix = m.group(1) # さんたちの直前の単語
        # ホワイトリスト: 親族・一般呼称
        if re.search(r'(お父|お母|お兄|お姉|おじ|おば|おじい|おばあ|みな|皆|お客|子ども|お子|奥|旦那)$', prefix):
            return m.group(0) # そのまま維持
        
        # 明らかな非人名パターン（チーム、組織、ポジション、属性、場所、一般名詞等）
        # 例: チーム、クラブ、代表、高校、大学、メンバー、陣、組、若手、ベテラン、主力、控え、投手、野手、打者、捕手、ファーム、軍、育成
        NON_NAME_SUFFIX = r'(?:チーム|軍|校|クラブ|代表|高校|大学|ユース|アカデミー|メンバー|陣|組|手|者|主力|控え|先発|ベンチ|ファーム|育成|層|側|勢)$'
        if re.search(NON_NAME_SUFFIX, prefix):
            return f"{prefix}選手たち"
        
        # 都道府県名・地名＋さんたち（例: 新潟さんたち、秋田さんたち、東京さんたち）
        PREF_PATTERN = r'(?:都|道|府|県|新潟|秋田|東京|大阪|愛知|福岡|宮城|広島|北海道|沖縄)$'
        if re.search(PREF_PATTERN, prefix):
            return f"{prefix}選手たち"
            
        return m.group(0)

    t = re.sub(r'([^\s、。！？（()）]{1,10})さんたち', santachi_repl, t)

    return t

test_cases = [
    # 今回発生したパターン
    ("ファームのさんたちが頑張っているにゃ", "ファームの選手たちが頑張っているにゃ"),
    ("調整中だったさんたちも合流したにゃ", "調整中だった選手たちも合流したにゃ"),
    ("ベンチ裏のさんたちへ声をかけたにゃ", "ベンチ裏の選手たちへ声をかけたにゃ"),
    ("合宿中のさんたちも順調にゃ", "合宿中の選手たちも順調にゃ"),
    ("高校のさんたちが甲子園を目指すにゃ", "高校の選手たちが甲子園を目指すにゃ"),
    ("契約更改したさんたちへの対応にゃ", "契約更改した選手たちへの対応にゃ"),
    ("戦うさんたちに熱い声援を送るにゃ", "戦う選手たちに熱い声援を送るにゃ"),
    ("挑むさんたちの姿に感動したにゃ", "挑む選手たちの姿に感動したにゃ"),
    ("新潟のさんたちも活躍したにゃ", "新潟の選手たちも活躍したにゃ"),
    ("両チームのさんたちに拍手を送りたいにゃ", "両チームの選手たちに拍手を送りたいにゃ"),
    ("出場するさんたちにエールを送るにゃ", "出場する選手たちにエールを送るにゃ"),
    ("さんのプレーに注目にゃ", "選手のプレーに注目にゃ"),
    # ホワイトリストで保護すべきもの
    ("みなさんたち、こんにちはにゃ", "みなさんたち、こんにちはにゃ"),
    ("お父さんたちも応援に来ていたにゃ", "お父さんたちも応援に来ていたにゃ"),
    ("山田さんたちと一緒に練習したにゃ", "山田さんたちと一緒に練習したにゃ"),
    ("大谷さんたちも笑顔を見せていたにゃ", "大谷さんたちも笑顔を見せていたにゃ"),
    # 孤立した助詞直後
    ("選手へのさんたちもいたにゃ", "選手への選手たちもいたにゃ"),
    ("期待される、さんたちにゃ", "期待される、選手たちにゃ"),
]

all_pass = True
for inp, expected in test_cases:
    res = repair_santachi_whitelist(inp)
    if res != expected:
        print(f"FAIL:\n  Input:    {inp}\n  Expected: {expected}\n  Got:      {res}")
        all_pass = False
    else:
        print(f"PASS: {inp} ➔ {res}")

if all_pass:
    print("\nALL 16 TESTS PASSED!")
