for dict_name, seasons in seasonal_phrases.items():
    # Find the end of the dictionary
    pattern = r'(const ' + dict_name + r' = \{[\s\S]*?\n    \]\n)\}'
    
    replacement = r'\1'
    for season, phrases in seasons.items():
        replacement += f'    ,\"{season}\": [\n'
        replacement += ',\n'.join(['        ' + p for p in phrases])
        replacement += '\n    ]\n'
    replacement += '}'
    
    content = re.sub(pattern, replacement, content, count=1)

with open('idle_phrases.js', 'w') as f:
    f.write(content)
